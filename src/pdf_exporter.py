"""
PDF exporter for CFE-style TRN tables.

Critical constraints (learned the hard way):
  - Action columns are capped by the renderer (~6). Never 15 skinny verb strips.
  - Table width MUST equal the printable page width — no left/right clipping.
  - Ingredient text wraps; action labels stay short and centered.
  - Full-width prep rows at the top of the table.
"""

from __future__ import annotations

import io
import os
from typing import Optional

from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER, TA_LEFT
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
    HRFlowable,
    KeepTogether,
)

from .models import TRNTable
from .trn_renderer import build_grid, TRNGrid, GridCell
from .sanitize import (
    scrub_inline,
    sanitize_title,
    sanitize_source_label,
    is_junk_ingredient_line,
    is_junk_step,
    assert_clean_output,
)

GREEN = colors.Color(0.13, 0.63, 0.35)
GREEN_DARK = colors.Color(0.10, 0.48, 0.27)
DARK_TEXT = colors.Color(0.07, 0.07, 0.07)
MUTED = colors.Color(0.30, 0.40, 0.32)
WHITE = colors.white


def export_pdf(
    table: TRNTable,
    path: Optional[str] = None,
    include_step_details: bool = True,
) -> bytes:
    # ── Final sanitizer pass — never let ad/URL junk reach the PDF ────────
    table = _sanitize_table_for_export(table)

    buffer = io.BytesIO()
    # Comfortable margins so nothing clips at the page edge
    left = right = 0.6 * inch
    top = bottom = 0.55 * inch
    page_w, page_h = letter
    usable_w = page_w - left - right

    clean_title = sanitize_title(table.title)
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        leftMargin=left,
        rightMargin=right,
        topMargin=top,
        bottomMargin=bottom,
        title=clean_title,
        author="Recipe Tables",
    )

    styles = _styles()
    story = []

    story.append(Paragraph(_xml_esc(clean_title), styles["title"]))
    meta_bits = []
    if table.servings:
        meta_bits.append(f"Serves {_xml_esc(scrub_inline(str(table.servings)))}")
    if table.scale_factor and abs(table.scale_factor - 1.0) > 1e-6:
        meta_bits.append(f"Scale {_format_scale(table.scale_factor)}")
    if table.substituted_protein:
        meta_bits.append(
            f"Protein: {_xml_esc(table.original_protein or '?')} → "
            f"{_xml_esc(table.substituted_protein)}"
        )
    if meta_bits:
        story.append(Paragraph(" · ".join(meta_bits), styles["meta"]))

    story.append(Spacer(1, 0.12 * inch))

    grid = build_grid(table)
    # Scream-test every cell before painting
    for row in grid.rows:
        for cell in row:
            if cell.skipped or not cell.text:
                continue
            problems = assert_clean_output(cell.text, "grid-cell")
            if problems:
                cell.text = scrub_inline(cell.text)
                # If still junk after scrub, blank the cell
                if assert_clean_output(cell.text, "grid-cell"):
                    if cell.kind == "action":
                        cell.text = cell.text  # already scrubbed
                    elif cell.kind != "ingredient":
                        cell.text = ""
                    else:
                        cell.text = scrub_inline(cell.text)

    story.append(_build_platypus_table(grid, usable_w))
    story.append(Spacer(1, 0.18 * inch))

    if include_step_details and table.steps:
        story.append(Paragraph("Method", styles["section"]))
        n = 0
        for step in table.steps:
            detail = scrub_inline(step.detail or step.action or "")
            if not detail or is_junk_step(detail):
                continue
            n += 1
            tag = "Prep" if step.is_header else str(n)
            body = _xml_esc(detail)
            if step.duration and step.duration not in detail:
                body += f" <i>({_xml_esc(scrub_inline(step.duration))})</i>"
            # Belt-and-suspenders
            if assert_clean_output(detail, "method"):
                continue
            story.append(Paragraph(f"<b>{tag}.</b> {body}", styles["step"]))

    if table.notes:
        notes = scrub_inline(table.notes)
        if notes and not assert_clean_output(notes, "notes"):
            story.append(Spacer(1, 0.1 * inch))
            story.append(Paragraph(f"<i>{_xml_esc(notes)}</i>", styles["meta"]))

    story.append(Spacer(1, 0.2 * inch))
    story.append(HRFlowable(width="100%", thickness=0.5, color=GREEN, spaceAfter=6))
    credit = (
        "Tabular Recipe Notation inspired by Michael Chu, "
        "Cooking for Engineers (2004) · Generated by Recipe Tables"
    )
    src = sanitize_source_label(table.source or "")
    if src and not assert_clean_output(src, "source"):
        # Only show host-style source, never marketing
        credit += f" · Source: {_xml_esc(src)}"
    story.append(Paragraph(credit, styles["footer"]))

    doc.build(story)
    pdf_bytes = buffer.getvalue()
    buffer.close()

    if path is not None:
        os.makedirs(os.path.dirname(os.path.abspath(path)) or ".", exist_ok=True)
        with open(path, "wb") as f:
            f.write(pdf_bytes)

    return pdf_bytes


def _flatten_grid(grid: TRNGrid):
    n_rows = len(grid.rows)
    n_cols = grid.n_cols
    matrix: list[list[Optional[GridCell]]] = [
        [None for _ in range(n_cols)] for _ in range(n_rows)
    ]
    covered = [[False] * n_cols for _ in range(n_rows)]
    spans: list[tuple] = []

    for r, row in enumerate(grid.rows):
        c = 0
        for cell in row:
            if cell.skipped:
                c += 1
                continue
            while c < n_cols and covered[r][c]:
                c += 1
            if c >= n_cols:
                break

            rs = min(max(1, cell.rowspan), n_rows - r)
            cs = min(max(1, cell.colspan), n_cols - c)

            matrix[r][c] = GridCell(
                text=cell.text,
                rowspan=rs,
                colspan=cs,
                kind=cell.kind,
                vertical=cell.vertical,
            )
            if rs > 1 or cs > 1:
                spans.append(("SPAN", (c, r), (c + cs - 1, r + rs - 1)))

            for dr in range(rs):
                for dc in range(cs):
                    rr, cc = r + dr, c + dc
                    if rr < n_rows and cc < n_cols:
                        covered[rr][cc] = True
            c += cs

    return matrix, spans


def _build_platypus_table(grid: TRNGrid, usable_width: float) -> Table:
    """
    Build a table that is EXACTLY usable_width wide so nothing clips.
    """
    matrix, spans = _flatten_grid(grid)
    n_rows = len(matrix)
    n_cols = grid.n_cols
    if n_rows == 0 or n_cols == 0:
        return Table([[""]])

    # --- column widths that ALWAYS sum to usable_width ---
    n_action = max(1, n_cols - 1)
    # Ingredient column gets ~40–50%; action cols share the rest equally
    if n_action <= 3:
        ing_frac = 0.42
    elif n_action <= 5:
        ing_frac = 0.38
    else:
        ing_frac = 0.34

    ing_w = usable_width * ing_frac
    action_w = (usable_width - ing_w) / n_action
    # Floor so action labels remain readable; shrink ingredient if needed
    min_action = 0.55 * inch
    if action_w < min_action and n_action > 0:
        action_w = min_action
        ing_w = max(usable_width - action_w * n_action, usable_width * 0.28)
        # Renormalize if still over (shouldn't with max 6 cols)
        total = ing_w + action_w * n_action
        if total > usable_width:
            scale = usable_width / total
            ing_w *= scale
            action_w *= scale

    col_widths = [ing_w] + [action_w] * n_action
    # Final safety: force exact sum
    drift = usable_width - sum(col_widths)
    col_widths[0] += drift

    ing_style = _cell_style(bold=False, center=False, size=8.5, leading=11)
    act_style = _cell_style(bold=True, center=True, size=8, leading=10)
    prep_style = _cell_style(bold=False, center=True, size=9.5, leading=12)

    data: list[list] = []
    style_cmds = [
        ("FONTNAME", (0, 0), (-1, -1), "Helvetica"),
        ("FONTSIZE", (0, 0), (-1, -1), 8.5),
        ("TEXTCOLOR", (0, 0), (-1, -1), DARK_TEXT),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("BACKGROUND", (0, 0), (-1, -1), WHITE),
        ("GRID", (0, 0), (-1, -1), 1.15, GREEN),
        ("BOX", (0, 0), (-1, -1), 2.5, GREEN),
        ("LEFTPADDING", (0, 0), (-1, -1), 5),
        ("RIGHTPADDING", (0, 0), (-1, -1), 5),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]

    for r in range(n_rows):
        row_data = []
        for c in range(n_cols):
            cell = matrix[r][c]
            if cell is None:
                row_data.append("")
                continue

            if cell.kind == "prep":
                row_data.append(Paragraph(_xml_esc(cell.text), prep_style))
            elif cell.kind == "ingredient":
                # Wrap long ingredient lines — prevents horizontal overflow
                row_data.append(Paragraph(_xml_esc(cell.text), ing_style))
                style_cmds.append(("ALIGN", (c, r), (c, r), "LEFT"))
            elif cell.kind == "action":
                txt = _format_action_pdf(cell.text, vertical=cell.vertical)
                row_data.append(Paragraph(f"<b>{txt}</b>", act_style))
                style_cmds.append(("ALIGN", (c, r), (c, r), "CENTER"))
            else:
                row_data.append("")
        data.append(row_data)

    t = Table(data, colWidths=col_widths, hAlign="LEFT")

    safe_spans = []
    for cmd in spans:
        (_, (c1, r1), (c2, r2)) = cmd
        if 0 <= r1 <= r2 < n_rows and 0 <= c1 <= c2 < n_cols:
            if not (r1 == r2 and c1 == c2):
                safe_spans.append(cmd)

    t.setStyle(TableStyle(style_cmds + safe_spans))
    return t


def _format_action_pdf(text: str, vertical: bool = False) -> str:
    """
    Format action label for PDF. ReportLab has no reliable vertical-rl,
    so we stack short phrases with <br/> for tall cells.
    """
    text = (text or "").strip()
    if not text:
        return ""
    # Already multi-line (bake / temp / time)
    if "\n" in text:
        return "<br/>".join(_xml_esc(p) for p in text.split("\n") if p.strip())

    words = text.split()
    if vertical and len(words) >= 2:
        # "fold in" → fold<br/>in
        return "<br/>".join(_xml_esc(w) for w in words)
    if vertical and len(text) <= 6:
        # single short verb — keep horizontal (letter-stacking looks awful)
        return _xml_esc(text)
    return _xml_esc(text)


def _styles():
    base = getSampleStyleSheet()
    return {
        "title": ParagraphStyle(
            "TRNTitle",
            parent=base["Heading1"],
            fontName="Helvetica-Bold",
            fontSize=16,
            textColor=GREEN_DARK,
            spaceAfter=3,
            leading=19,
        ),
        "meta": ParagraphStyle(
            "TRNMeta",
            parent=base["Normal"],
            fontName="Helvetica",
            fontSize=9,
            textColor=MUTED,
            spaceAfter=2,
        ),
        "section": ParagraphStyle(
            "TRNSection",
            parent=base["Heading2"],
            fontName="Helvetica-Bold",
            fontSize=11,
            textColor=GREEN_DARK,
            spaceBefore=4,
            spaceAfter=5,
        ),
        "step": ParagraphStyle(
            "TRNStep",
            parent=base["Normal"],
            fontName="Helvetica",
            fontSize=9,
            textColor=DARK_TEXT,
            leading=12,
            spaceAfter=3,
            leftIndent=4,
        ),
        "footer": ParagraphStyle(
            "TRNFooter",
            parent=base["Normal"],
            fontName="Helvetica-Oblique",
            fontSize=7.5,
            textColor=MUTED,
            alignment=TA_CENTER,
        ),
    }


def _cell_style(
    bold: bool = False,
    center: bool = False,
    size: float = 9,
    leading: float = 11,
) -> ParagraphStyle:
    return ParagraphStyle(
        f"cell_{bold}_{center}_{size}_{leading}",
        fontName="Helvetica-Bold" if bold else "Helvetica",
        fontSize=size,
        leading=leading,
        textColor=DARK_TEXT,
        alignment=TA_CENTER if center else TA_LEFT,
        wordWrap="CJK",  # aggressive wrap so long ings never blow width
    )


def _sanitize_table_for_export(table: TRNTable) -> TRNTable:
    """Deep-clean a table copy so PDF never prints ad/URL garbage."""
    from copy import deepcopy

    t = deepcopy(table)
    t.title = sanitize_title(t.title)
    if t.servings:
        t.servings = scrub_inline(str(t.servings))
    if t.notes:
        t.notes = scrub_inline(t.notes)
        if assert_clean_output(t.notes, "notes") or is_junk_step(t.notes):
            t.notes = ""
    t.source = sanitize_source_label(t.source or "")

    clean_ings = []
    for ing in t.ingredients:
        ing.name = scrub_inline(ing.name)
        if ing.name and not is_junk_ingredient_line(ing.name):
            if not assert_clean_output(ing.name, "ing"):
                clean_ings.append(ing)
            else:
                ing.name = scrub_inline(ing.name)
                if ing.name and not is_junk_ingredient_line(ing.name):
                    clean_ings.append(ing)
    t.ingredients = clean_ings

    clean_steps = []
    for step in t.steps:
        step.action = scrub_inline(step.action)
        step.detail = scrub_inline(step.detail)
        if is_junk_step(step.detail or step.action):
            continue
        if assert_clean_output(step.detail or "", "step") or assert_clean_output(
            step.action or "", "step"
        ):
            step.detail = scrub_inline(step.detail)
            step.action = scrub_inline(step.action)
            if is_junk_step(step.detail or step.action):
                continue
        clean_steps.append(step)
    t.steps = clean_steps
    return t


def _xml_esc(s: str) -> str:
    return (s or "").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def _format_scale(f: float) -> str:
    mapping = {0.5: "½×", 1.0: "1×", 1.5: "1½×", 2.0: "2×", 3.0: "3×"}
    for k, v in mapping.items():
        if abs(f - k) < 1e-6:
            return v
    return f"{f:g}×"
